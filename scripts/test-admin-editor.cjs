const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),ts=require('typescript');
const {createRequire}=require('node:module');
const schema=require('../shared/gacha/catalog');
const seed=require('../shared/gacha/seed-catalog.json');
const file=path.resolve('src/lib/admin-catalog-editor.ts'),moduleResult={exports:{}};
new Function('require','module','exports',ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(createRequire(file),moduleResult,moduleResult.exports);
const edit=moduleResult.exports;
const image={uri:'https://example.com/new-animal.png'};
const withAnimal=edit.registerAnimal(seed,{id:'new_epic_animal',name:'새 에픽 동물',grade:'EP',image});
schema.validateCatalog(withAnimal);schema.assertCompatible(seed,withAnimal);
assert.equal(edit.storedAnimals(withAnimal).length,edit.storedAnimals(seed).length+1);
assert.ok(edit.storedAnimals(withAnimal).some(ch=>ch.id==='new_epic_animal'&&ch.grade==='EP'&&ch.eligible));
assert.throws(()=>edit.registerAnimal(withAnimal,{id:'new_epic_animal',name:'덮어쓰기',grade:'N',image}),/이미 등록/);
let banner=edit.newBanner(withAnimal,'admin_test');
assert.throws(()=>schema.validateCatalog(edit.putBanner(withAnimal,banner)),/확률|선택/);
banner=edit.selectAnimals(withAnimal,banner,['mouse','cow','premium_mouse']);
const next=edit.putBanner(withAnimal,banner);
schema.validateCatalog(next);schema.assertCompatible(seed,next);
assert.deepEqual(next.collections,withAnimal.collections,'creating a draw never invents a duplicate animal or collection');
const compiled=schema.compileCatalog(next).banners.find(b=>b.id==='admin_test');
assert.deepEqual(compiled.characterIds,['mouse','cow','premium_mouse']);
for(const [roll,within,expected] of [[0,0,'mouse'],[0.49,.99,'cow'],[.9,0,'premium_mouse']]){
 const rolls=[roll,within];assert.equal(schema.pickCharacter(next,banner,()=>rolls.shift()).id,expected);
}
const evolved=edit.storedAnimals(next).find(ch=>!ch.eligible&&ch.grade==='EP');
assert.ok(!edit.selectAnimals(next,banner,[evolved.id,'mouse']).characterIds.includes(evolved.id));
const forged=structuredClone(next);forged.banners[0].characterIds.push(evolved.id);
assert.throws(()=>schema.validateCatalog(forged),/진화 전용/);
const selectedOnly=edit.selectAnimals(next,banner,['cow']);
assert.equal(schema.pickCharacter(next,selectedOnly,()=>.99).id,'cow','unselected animals in the same grade never appear');
const bannerFile=path.resolve('src/constants/banners.ts'),bannerModule={exports:{}};
const characters=Object.fromEntries(next.collections.flatMap(c=>c.characters.map(ch=>[ch.id,{...ch,grade:c.grade,collection:c.id}])));
new Function('require','module','exports',ts.transpileModule(fs.readFileSync(bannerFile,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(id=>id==='./characters'?{CHARACTER_BY_ID:characters}:id==='./gacha.generated'?{COLLECTION_DATA:next.collections}:createRequire(bannerFile)(id),bannerModule,bannerModule.exports);
bannerModule.exports.rebuildBanners(next.banners);
const playerBanner=bannerModule.exports.BANNERS.find(b=>b.id==='admin_test');assert.ok(playerBanner);
for(let i=0;i<100;i++)assert.ok(compiled.characterIds.includes(bannerModule.exports.pickFromBanner(playerBanner).id));
bannerModule.exports.rebuildBanners([]);assert.ok(!bannerModule.exports.BANNERS.some(b=>b.id==='admin_test'));
const zero=edit.setGradeWeight(next,banner,'N',0);
assert.throws(()=>schema.validateCatalog(edit.putBanner(next,zero)),/100%|확률/);
assert.deepEqual(seed,require('../shared/gacha/seed-catalog.json'),'original catalog is untouched');
console.log('PASS server-animal registration, new banners without fake animals, exact selected pools, grade odds, evolution/baby exclusion, duplicate protection and immutable originals');
